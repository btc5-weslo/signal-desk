#!/usr/bin/env bash
# Generate shared/ts/index.ts from every *.schema.json in this directory.
# Usage: bash shared/generate_ts.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
OUT="$ROOT/ts/index.ts"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

shopt -s nullglob
schemas=("$ROOT"/*.schema.json)
if [[ ${#schemas[@]} -eq 0 ]]; then
  echo "no *.schema.json files in $ROOT" >&2
  exit 1
fi

if [[ -f "$ROOT/export_schema.py" ]]; then
  if [[ -x "$ROOT/../backend/.venv/bin/python" ]]; then
    "$ROOT/../backend/.venv/bin/python" "$ROOT/export_schema.py"
  else
    python3 "$ROOT/export_schema.py"
  fi
fi

# Deduplicate identical schema files (e.g. backtest.json + backtest_result.json).
declare -A seen_hash
unique=()
for schema in "${schemas[@]}"; do
  hash="$(cksum "$schema" | awk '{print $1" "$2}')"
  if [[ -n "${seen_hash[$hash]+x}" ]]; then
    echo "skip duplicate schema $(basename "$schema") (same as ${seen_hash[$hash]})"
    continue
  fi
  seen_hash[$hash]="$(basename "$schema")"
  unique+=("$schema")
done

{
  echo "// Auto-generated from JSON Schema. Do not edit by hand."
  echo "// Regenerate: bash shared/generate_ts.sh"
  echo ""
  for schema in "${unique[@]}"; do
    echo "// --- $(basename "$schema") ---"
    npx --yes json-schema-to-typescript@15.0.4 "$schema"
    echo
  done
} > "$TMP/raw.ts"

node --input-type=module - "$TMP/raw.ts" "$OUT" << 'NODE'
import fs from "node:fs";
import path from "node:path";

const src = fs.readFileSync(process.argv[2], "utf8");
const lines = src.split("\n");
const out = [];
const seen = new Map(); // type name -> text

function isFileBanner(line) {
  return (
    line.startsWith("/* eslint-disable") ||
    line.includes("automatically generated by json-schema-to-typescript") ||
    line.includes("DO NOT MODIFY IT BY HAND") ||
    line.includes("modify the source JSONSchema file") ||
    line.includes("run json-schema-to-typescript to regenerate")
  );
}

let i = 0;
while (i < lines.length) {
  const line = lines[i];

  if (line.trim() === "") {
    i++;
    continue;
  }

  // Keep our generator headers; drop the per-file tool banner.
  if (line.startsWith("//")) {
    if (!isFileBanner(line)) out.push(line);
    i++;
    continue;
  }

  if (line.trim().startsWith("/*")) {
    let j = i;
    const block = [];
    while (j < lines.length) {
      block.push(lines[j]);
      if (lines[j].includes("*/")) break;
      j++;
    }
    if (block.some(isFileBanner)) {
      i = j + 1;
      continue;
    }
  }

  // Optional JSDoc attached to the following export.
  const start = i;
  if (line.trim().startsWith("/*")) {
    while (i < lines.length && !lines[i].includes("*/")) i++;
    i++; // closing */
    while (i < lines.length && lines[i].trim() === "") i++;
  }

  if (i >= lines.length || !lines[i].startsWith("export ")) {
    // Orphan comment; skip.
    i = Math.max(i, start + 1);
    continue;
  }

  let end = i;
  const exportLine = lines[i];
  const open = (exportLine.match(/{/g) || []).length;
  const close = (exportLine.match(/}/g) || []).length;
  if (open > close) {
    end++;
    let depth = open - close;
    while (end < lines.length && depth > 0) {
      const l = lines[end];
      depth += (l.match(/{/g) || []).length;
      depth -= (l.match(/}/g) || []).length;
      end++;
    }
    end--; // last line of the block
  } else if (/^export type /.test(exportLine) && !exportLine.trimEnd().endsWith(";")) {
    // Multi-line union/alias: keep lines until the statement's closing ';'.
    while (end + 1 < lines.length && !lines[end].trimEnd().endsWith(";")) end++;
  }

  const block = lines.slice(start, end + 1).join("\n");
  const m = exportLine.match(/export (?:interface|type|enum) (\w+)/);
  if (m) {
    const name = m[1];
    const prev = seen.get(name);
    if (prev !== undefined) {
      // Compare the export itself, ignoring JSDoc, so attached comments don't
      // make identical types look like conflicts.
      const strip = (s) => s.replace(/\/\*\*[\s\S]*?\*\//g, "").trim();
      if (strip(prev) !== strip(block)) {
        console.error(`conflicting TypeScript definitions for ${name}`);
        console.error("--- previous ---");
        console.error(prev);
        console.error("--- new ---");
        console.error(block);
        process.exit(1);
      }
      i = end + 1;
      continue;
    }
    seen.set(name, block);
  }
  out.push(block);
  i = end + 1;
}

fs.mkdirSync(path.dirname(process.argv[3]), { recursive: true });
const text = out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
fs.writeFileSync(process.argv[3], text);
console.log("wrote", process.argv[3]);
NODE
